import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import org.jetbrains.kotlin.konan.target.Family

plugins {
    id("gekko-format")
    kotlin("multiplatform")
    kotlin("plugin.serialization")
}

group = providers.gradleProperty("GROUP").get()

version = providers.gradleProperty("VERSION_NAME").get()

kotlin {
    jvm()
    macosArm64()
    linuxX64()

    targets.withType<KotlinNativeTarget>().configureEach {
        binaries.executable {
            baseName = "gekko"
            entryPoint = "com.jakala.gekko.cli.main"
        }
        // clikt and clikt-mordant both define Context.selfAndAncestors(); lld on Linux refuses the duplicate, the
        // macOS linker does not care
        if (konanTarget.family == Family.LINUX) {
            binaries.all { linkerOpts("--allow-multiple-definition") }
        }
    }

    sourceSets {
        all { languageSettings.optIn("kotlinx.cinterop.ExperimentalForeignApi") }
        commonMain.dependencies {
            implementation(project(":protocol"))
            implementation(libs.kotlinx.serialization.json)
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.ktor.client.core)
            implementation(libs.ktor.client.cio)
            implementation(libs.clikt)
            implementation(libs.kaml)
            implementation(libs.okio)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(libs.kotlinx.coroutines.test)
        }
        // The servers of the Android agent and runner: the client is tested against the real thing, not a copy of it
        jvmTest.dependencies { implementation(project(":transport-jvm")) }
    }
}

tasks.register<JavaExec>("gekkoJvm") {
    group = "application"
    mainClass.set("com.jakala.gekko.cli.MainKt")
    val jvmMain = kotlin.jvm().compilations.getByName("main")
    classpath(jvmMain.output.allOutputs, jvmMain.runtimeDependencyFiles)
}

// The scripts of the web platform ship inside the binary: the CLI writes them next to Playwright when a session starts
val generateWebAssets by tasks.registering {
    val scripts = layout.projectDirectory.dir("../agent-web")
    val output = layout.buildDirectory.dir("generated/web")
    inputs.files(scripts.file("page.js"), scripts.file("bridge.mjs"))
    outputs.dir(output)
    doLast {
        fun literal(file: File): String {
            val text = file.readText()
            val escaped = StringBuilder()
            for (char in text) {
                when {
                    char == '\\' -> escaped.append("\\\\")
                    char == '"' -> escaped.append("\\\"")
                    char == '$' -> escaped.append("\\$")
                    char == '\n' -> escaped.append("\\n")
                    char == '\r' -> escaped.append("\\r")
                    char == '\t' -> escaped.append("\\t")
                    char.code < 32 || char.code > 126 -> escaped.append("\\u%04x".format(char.code))
                    else -> escaped.append(char)
                }
            }
            return "\"" + escaped + "\""
        }
        val file = output.get().file("com/jakala/gekko/cli/WebAssets.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package com.jakala.gekko.cli\n\n/** The files of agent-web, generated by the build. */\n" +
                "internal object WebAssets {\n" +
                "    const val PAGE_SCRIPT = ${literal(scripts.file("page.js").asFile)}\n\n" +
                "    const val BRIDGE_SCRIPT = ${literal(scripts.file("bridge.mjs").asFile)}\n}\n"
        )
    }
}

kotlin.sourceSets.commonMain { kotlin.srcDir(generateWebAssets.map { it.outputs.files.singleFile }) }
